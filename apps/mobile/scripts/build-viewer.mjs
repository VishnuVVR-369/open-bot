import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [path.join(root, "src/computer/viewer.ts")],
  bundle: true,
  platform: "browser",
  format: "esm",
  target: "chrome100",
  minify: true,
  write: false,
  legalComments: "inline",
});
const script = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const license = await readFile(path.join(root, "node_modules/@novnc/novnc/docs/LICENSE.MPL-2.0"), "utf8");
const notice = `noVNC 1.7.0, MPL-2.0. Unmodified library source: https://github.com/novnc/noVNC/tree/v1.7.0\n${license}`;
const css =
  "html,body{margin:0;width:100%;height:100%;overflow:hidden;background:#101117;touch-action:none}#host{position:absolute;inset:0;transform-origin:0 0}#cursor{position:absolute;width:14px;height:14px;border:2px solid white;border-radius:50%;box-shadow:0 0 2px black;pointer-events:none;display:none;z-index:2}";
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src wss: ws:; img-src data: blob:"><style>${css}</style></head><body><!-- ${notice.replaceAll("--", "- -")} --><div id="host"></div><div id="cursor"></div><script type="module">${script}</script></body></html>`;
const generated = `// Generated by scripts/build-viewer.mjs. Do not edit.\nexport const viewerHtml = ${JSON.stringify(html)};\n`;
const output = path.join(root, "src/computer/viewer-html.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== generated)
    throw new Error("Run pnpm build:viewer to regenerate the bundled viewer.");
} else await writeFile(output, generated);
